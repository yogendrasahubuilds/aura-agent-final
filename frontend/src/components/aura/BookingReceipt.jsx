import { Card } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { CheckCircle2, Sparkles, Download } from "lucide-react";
import { downloadBookingPdf } from "@/lib/pdf";

const fmt = (n) => new Intl.NumberFormat("en-IN", { maximumFractionDigits: 2 }).format(n);

export default function BookingReceipt({ receipt, onNew }) {
  const { booking_id, intent, option, quantity, amount, verified, status, extra, seats } = receipt;
  const title = intent === "movie" ? option.cinema : intent === "hotel" ? option.hotel : `${option.airline} ${option.flight_no}`;

  return (
    <Card className="p-6 bg-white border-2 border-dashed border-emerald-400 shadow-lg" data-testid="booking-receipt">
      <div className="flex items-center justify-between mb-3">
        <div className="flex items-center gap-2">
          <div className="w-10 h-10 rounded-full bg-emerald-500 flex items-center justify-center text-white">
            <CheckCircle2 className="w-5 h-5" />
          </div>
          <div>
            <h3 className="font-heading font-extrabold text-slate-900">Simulated Booking Confirmed</h3>
            <p className="text-[11px] text-slate-500">Status: {status} · Verified: {verified ? "Yes" : "No"}</p>
          </div>
        </div>
        <Badge className="bg-emerald-100 text-emerald-800 border-emerald-300 border">DEMO</Badge>
      </div>

      <div className="bg-gradient-to-r from-indigo-50 via-white to-cyan-50 rounded-xl border border-indigo-200 p-5 mt-3">
        <p className="text-[11px] uppercase tracking-wider text-slate-500">Booking ID</p>
        <p className="font-mono font-bold text-2xl text-slate-900 tracking-wider" data-testid="booking-id">{booking_id}</p>

        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 mt-5 text-sm">
          <div>
            <p className="text-xs text-slate-500">Type</p>
            <p className="font-semibold capitalize">{intent}</p>
          </div>
          <div>
            <p className="text-xs text-slate-500">Selection</p>
            <p className="font-semibold">{title}</p>
          </div>
          {intent === "movie" && (
            <>
              <div><p className="text-xs text-slate-500">Movie</p><p className="font-semibold">{option.movie}</p></div>
              <div><p className="text-xs text-slate-500">Show time</p><p className="font-semibold">{option.time} · {option.screen}</p></div>
              <div><p className="text-xs text-slate-500">Tickets</p><p className="font-semibold">{quantity}</p></div>
              {seats && seats.length > 0 && (
                <div><p className="text-xs text-slate-500">Seats</p><p className="font-mono font-semibold">{seats.join(", ")}</p></div>
              )}
            </>
          )}
          {intent === "hotel" && (
            <>
              <div><p className="text-xs text-slate-500">Room type</p><p className="font-semibold">{option.room_type}</p></div>
              <div><p className="text-xs text-slate-500">Nights</p><p className="font-semibold">{extra?.nights || 1}</p></div>
              <div><p className="text-xs text-slate-500">Guests</p><p className="font-semibold">{quantity}</p></div>
            </>
          )}
          {intent === "flight" && (
            <>
              <div><p className="text-xs text-slate-500">Route</p><p className="font-semibold">{option.source} → {option.destination}</p></div>
              <div><p className="text-xs text-slate-500">Departure</p><p className="font-semibold">{option.departure}</p></div>
              <div><p className="text-xs text-slate-500">Passengers</p><p className="font-semibold">{quantity}</p></div>
            </>
          )}
        </div>

        <div className="border-t border-dashed border-slate-300 mt-5 pt-4 flex justify-between items-end">
          <div>
            <p className="text-xs text-slate-500">Total paid (simulated)</p>
            <p className="font-heading font-extrabold text-2xl text-slate-900">₹{fmt(amount.total)}</p>
          </div>
          <Sparkles className="w-10 h-10 text-indigo-300" />
        </div>
      </div>

      <div className="flex gap-2 mt-5 flex-wrap">
        <Button onClick={() => downloadBookingPdf(receipt)} className="bg-indigo-600 hover:bg-indigo-700 text-white" data-testid="download-ticket-btn">
          <Download className="w-4 h-4 mr-1.5" /> Download PDF Ticket
        </Button>
        <Button variant="outline" onClick={onNew} data-testid="new-booking-btn">
          Start a new request
        </Button>
      </div>
      <p className="text-[11px] text-slate-500 mt-3">
        This is a mock booking generated by AURA for demonstration. No real inventory was reserved and no payment was processed.
      </p>
    </Card>
  );
}
