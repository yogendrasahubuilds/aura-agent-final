import jsPDF from "jspdf";
import { makeBookingQr } from "@/lib/qr";

const fmt = (value) => new Intl.NumberFormat("en-IN", { maximumFractionDigits: 2 }).format(Number(value) || 0);
const text = (value, fallback = "—") => String(value ?? fallback);

function addHeader(doc, width, label) {
  doc.setFillColor(49, 46, 129);
  doc.rect(0, 0, width, 112, "F");
  doc.setFillColor(79, 70, 229);
  doc.triangle(width * 0.48, 0, width, 0, width, 112, "F");
  doc.setFillColor(8, 145, 178);
  doc.triangle(width * 0.74, 0, width, 0, width, 112, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(25);
  doc.text("AURA", 42, 46);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.text("Autonomous Universal Resource Agent", 43, 62);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.text(label, width - 42, 45, { align: "right" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.text("Simulated document · No real reservation or payment", width - 42, 61, { align: "right" });
}

function addFooter(doc, width, height) {
  const pages = doc.internal.getNumberOfPages();
  for (let page = 1; page <= pages; page += 1) {
    doc.setPage(page);
    doc.setDrawColor(203, 213, 225);
    doc.line(42, height - 42, width - 42, height - 42);
    doc.setTextColor(100, 116, 139);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    doc.text("Simulated plan generated by AURA. No real bookings or payments.", 42, height - 27);
    doc.text(String(page), width - 42, height - 27, { align: "right" });
  }
}

function addQrCode(doc, bookingId, x, y, size = 92) {
  const matrix = makeBookingQr(bookingId);
  const cell = size / matrix.length;
  doc.setFillColor(255, 255, 255);
  doc.rect(x - 5, y - 5, size + 10, size + 10, "F");
  doc.setFillColor(23, 37, 84);
  matrix.forEach((row, rowIndex) => row.forEach((enabled, columnIndex) => {
    if (enabled) doc.rect(x + columnIndex * cell, y + rowIndex * cell, cell, cell, "F");
  }));
}

function titleFor(intent, option) {
  if (intent === "movie") return `${option.movie || "Movie"} · ${option.cinema || ""}`;
  if (intent === "hotel") return option.hotel || "Hotel";
  if (intent === "flight") return `${option.airline || "Flight"} ${option.flight_no || ""}`.trim();
  return option.train_name || option.operator || option.match || option.event || "Booking";
}

export function downloadBookingPdf(receipt) {
  const {
    booking_id: bookingId, intent, option = {}, quantity = 1, amount = {}, extra = {},
    created_at: createdAt, payment_timestamp: paymentTimestamp, transaction_id: transactionId,
    payment_method: paymentMethod, pnr, passengers = [], seats = [],
    contact = {},
    fare_breakdown: fareBreakdown = amount.breakdown || [],
  } = receipt;
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const width = doc.internal.pageSize.getWidth();
  const height = doc.internal.pageSize.getHeight();
  const left = 42;
  const right = width - left;
  addHeader(doc, width, "SIMULATED E-TICKET");

  let y = 140;
  doc.setTextColor(79, 70, 229);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(8);
  doc.text("BOOKING CONFIRMED", left, y);
  y += 23;
  doc.setTextColor(15, 23, 42);
  doc.setFont("courier", "bold");
  doc.setFontSize(17);
  doc.text(bookingId, left, y);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.text(titleFor(intent, option), right, y, { align: "right", maxWidth: 270 });
  y += 25;

  const metaRows = [];
  if (["flight", "train", "bus"].includes(intent)) {
    metaRows.push(["Route", `${text(option.source)} → ${text(option.destination)}`]);
    metaRows.push(["Departure / arrival", `${text(option.departure)} → ${text(option.arrival)} · ${text(option.duration)}`]);
    metaRows.push(["Class / seat", `${text(option.class)}${seats.length ? ` · ${seats.join(", ")}` : ""}`]);
  } else if (intent === "hotel") {
    metaRows.push(["Stay", `${extra.nights || 1} night(s) · ${extra.rooms || 1} room(s) · ${quantity} guest(s)`]);
    metaRows.push(["Room", `${text(option.room_type)} · ${text(option.location)}`]);
  } else if (["cricket", "concert"].includes(intent)) {
    metaRows.push(["Venue", `${text(option.stadium || option.venue)} · ${text(option.city)}`]);
    metaRows.push(["Date / time / stand", `${text(option.date)} · ${text(option.departure)}–${text(option.arrival)} · ${text(option.class)}`]);
  } else if (intent === "movie") {
    metaRows.push(["Movie / show", `${text(option.movie)} · ${text(option.time)} · ${text(option.screen)}`]);
    metaRows.push(["Seats", seats.length ? seats.join(", ") : `${quantity} ticket(s)`]);
  }
  if (pnr) metaRows.push(["PNR", pnr]);
  metaRows.push(["Transaction", transactionId || "Not available"]);
  metaRows.push(["Payment / booked", `${paymentMethod || "Simulated"} · ${paymentTimestamp ? new Date(paymentTimestamp).toLocaleString("en-IN") : createdAt ? new Date(createdAt).toLocaleString("en-IN") : "—"}`]);
  if (contact.email) metaRows.push(["Contact email", contact.email]);
  if (contact.phone) metaRows.push(["Contact phone", contact.phone]);

  doc.setFillColor(248, 250, 252);
  doc.roundedRect(left, y, right - left, 8 + metaRows.length * 20, 8, 8, "F");
  let rowY = y + 21;
  metaRows.forEach(([label, value]) => {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(label, left + 12, rowY);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(30, 41, 59);
    doc.text(doc.splitTextToSize(text(value), right - left - 185), left + 145, rowY);
    rowY += 20;
  });
  y += metaRows.length * 20 + 28;

  const pageBreak = () => {
    doc.addPage();
    addHeader(doc, width, "SIMULATED E-TICKET · CONTINUED");
    y = 140;
  };
  if (passengers.length) {
    if (y > height - 170) pageBreak();
    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    doc.setTextColor(30, 27, 75);
    doc.text("Passenger / guest details", left, y);
    y += 18;
    const passengerRows = [["Name", "Age", "Gender"], ...passengers.map((person) => [text(person.name), String(person.age ?? "—"), text(person.gender)])];
    passengerRows.forEach((row, index) => {
      if (y > height - 115) pageBreak();
      if (index === 0) {
        doc.setFillColor(238, 242, 255);
        doc.rect(left, y - 11, right - left, 20, "F");
      }
      doc.setFont("helvetica", index === 0 ? "bold" : "normal");
      doc.setFontSize(8);
      doc.setTextColor(index === 0 ? 67 : 51, index === 0 ? 56 : 65, index === 0 ? 202 : 85);
      doc.text(text(row[0]), left + 8, y + 2);
      doc.text(text(row[1]), left + 300, y + 2);
      doc.text(text(row[2]), left + 390, y + 2);
      y += 20;
    });
    y += 14;
  }

  if (y > height - 220) pageBreak();
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(30, 27, 75);
  doc.text("Fare breakdown", left, y);
  y += 20;
  const rows = fareBreakdown.length ? fareBreakdown.map((line) => [line.label, line.amount]) : [
    ["Base fare", amount.subtotal],
    [`GST (${amount.gst_rate ?? 18}%)`, amount.tax],
  ];
  rows.push(["Subtotal", amount.subtotal], ["Taxes and fees", amount.fees], ["Discount", -Number(amount.discount || 0)]);
  rows.forEach(([label, value]) => {
    if (y > height - 125) pageBreak();
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(71, 85, 105);
    doc.text(text(label), left, y);
    doc.text(`Rs ${fmt(value)}`, right, y, { align: "right" });
    y += 17;
  });
  doc.setDrawColor(199, 210, 254);
  doc.line(left, y - 6, right, y - 6);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.setTextColor(15, 23, 42);
  doc.text("Grand total", left, y + 8);
  doc.text(`Rs ${fmt(amount.total)}`, right, y + 8, { align: "right" });

  if (y > height - 180) pageBreak();
  const qrY = Math.min(height - 142, y + 32);
  addQrCode(doc, bookingId, right - 92, qrY, 76);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(7);
  doc.setTextColor(100, 116, 139);
  doc.text("BOOKING ID QR", right - 54, qrY + 88, { align: "center" });
  doc.text("Cancellation: simulated bookings cannot be cancelled or exchanged.", left, Math.min(height - 60, qrY + 24));
  addFooter(doc, width, height);
  doc.save(`${bookingId}.pdf`);
}
